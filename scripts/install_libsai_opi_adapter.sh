# Install libsai_opi_adapter.so as SONiC's vendor SAI library (libsai.so)
# and point it at the DPU OPI gRPC server.
#
#   sudo ./scripts/install_libsai_opi_adapter.sh \
#       --lib build/libsai_opi_adapter.so \
#       --opi-server 192.168.100.1:50051 \
#       --opi-snap 192.168.100.1:50052
#
# syncd dlopens libsai.so. This script backs up the vendor copy, installs
# ours, writes OPI_SERVER_ADDRESS / OPI_SNAP_ADDRESS so sai_api_initialize
# can open CloudInfra (:50051) and SNAP (:50052) channels.
set -euo pipefail

OPI_SERVER_ADDRESS="${OPI_SERVER_ADDRESS:-192.168.100.1:50051}"
OPI_SNAP_ADDRESS="${OPI_SNAP_ADDRESS:-}"
ADAPTER_SO=""
SYNCD_CONTAINER="${SYNCD_CONTAINER:-syncd}"
RESTART_SYNCD=1

usage() {
  cat <<'EOF'
Usage: install_libsai_opi_adapter.sh --lib <libsai_opi_adapter.so> [options]

  --lib PATH              Compiled adapter (default: search build/)
  --opi-server HOST:PORT  OPI_SERVER_ADDRESS (default: 192.168.100.1:50051)
  --opi-snap HOST:PORT    OPI_SNAP_ADDRESS (default: sibling :50052)
  --container NAME        syncd docker name (default: syncd)
  --no-restart            Do not restart the syncd container
EOF
  exit 1
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --lib) ADAPTER_SO="$2"; shift 2 ;;
    --opi-server) OPI_SERVER_ADDRESS="$2"; shift 2 ;;
    --opi-snap) OPI_SNAP_ADDRESS="$2"; shift 2 ;;
    --container) SYNCD_CONTAINER="$2"; shift 2 ;;
    --no-restart) RESTART_SYNCD=0; shift ;;
    -h|--help) usage ;;
    *) echo "unknown arg: $1" >&2; usage ;;
  esac
done

if [[ -z "${OPI_SNAP_ADDRESS}" ]]; then
  OPI_SNAP_ADDRESS="${OPI_SERVER_ADDRESS%:*}:50052"
fi

if [[ -z "${ADAPTER_SO}" ]]; then
  for cand in \
      ./build/libsai_opi_adapter.so \
      ./build/lib/libsai_opi_adapter.so \
      /usr/local/lib/libsai_opi_adapter.so; do
    if [[ -f "${cand}" ]]; then
      ADAPTER_SO="${cand}"
      break
    fi
  done
fi
[[ -f "${ADAPTER_SO}" ]] || { echo "adapter .so not found; pass --lib" >&2; exit 1; }

if [[ "${EUID}" -ne 0 ]]; then
  echo "re-run as root (syncd library lives under /usr/lib and /etc)" >&2
  exit 1
fi

timestamp="$(date -u +%Y%m%dT%H%M%SZ)"
backup_dir="/var/lib/sai-opi/backup-${timestamp}"
mkdir -p "${backup_dir}"

write_opi_env() {
  local dest="$1"
  mkdir -p "$(dirname "${dest}")"
  cat > "${dest}" <<EOF
# Generated by install_libsai_opi_adapter.sh
OPI_SERVER_ADDRESS=${OPI_SERVER_ADDRESS}
OPI_SNAP_ADDRESS=${OPI_SNAP_ADDRESS}
EOF
  chmod 0644 "${dest}"
}

merge_sai_profile() {
  local profile="$1"
  mkdir -p "$(dirname "${profile}")"
  touch "${profile}"
  if grep -q '^OPI_SERVER_ADDRESS=' "${profile}" 2>/dev/null; then
    sed -i "s|^OPI_SERVER_ADDRESS=.*|OPI_SERVER_ADDRESS=${OPI_SERVER_ADDRESS}|" "${profile}"
  else
    printf '\nOPI_SERVER_ADDRESS=%s\n' "${OPI_SERVER_ADDRESS}" >> "${profile}"
  fi
  if grep -q '^OPI_SNAP_ADDRESS=' "${profile}" 2>/dev/null; then
    sed -i "s|^OPI_SNAP_ADDRESS=.*|OPI_SNAP_ADDRESS=${OPI_SNAP_ADDRESS}|" "${profile}"
  else
    printf '\nOPI_SNAP_ADDRESS=%s\n' "${OPI_SNAP_ADDRESS}" >> "${profile}"
  fi
}

install_host_lib() {
  local dest_dir="$1"
  mkdir -p "${dest_dir}"
  local dest="${dest_dir}/libsai.so"
  if [[ -e "${dest}" || -L "${dest}" ]]; then
    cp -a "${dest}" "${backup_dir}/$(echo "${dest}" | tr '/' '_')"
  fi
  # Keep the adapter under its own name and point libsai.so at it (SONAME
  # that syncd dlopens is still libsai.so).
  install -m 0755 "${ADAPTER_SO}" "${dest_dir}/libsai_opi_adapter.so"
  ln -sfn libsai_opi_adapter.so "${dest}"
  echo "installed ${dest} -> libsai_opi_adapter.so"
}

# --- Host paths (bare-metal syncd, or files bind-mounted into docker) ---
# /etc/sonic is bind-mounted into the syncd container and survives recreate.
write_opi_env /etc/sonic/opi.env
write_opi_env /etc/sai.d/opi.env
merge_sai_profile /etc/sai.d/sai.profile

# Multiarch + legacy libsai locations used by SONiC images.
host_libdirs=("/usr/lib" "/usr/lib/$(uname -m)-linux-gnu")
if [[ "$(uname -m)" == "x86_64" ]]; then
  host_libdirs+=("/usr/lib/x86_64-linux-gnu")
elif [[ "$(uname -m)" == "aarch64" ]]; then
  host_libdirs+=("/usr/lib/aarch64-linux-gnu")
fi

for d in "${host_libdirs[@]}"; do
  if [[ -d "${d}" ]]; then
    install_host_lib "${d}"
  fi
done
command -v ldconfig >/dev/null && ldconfig || true

# Golden copy for scripts/enable-persistent-adapter.sh (survives image pull).
mkdir -p /var/lib/sai-opi
install -m 0755 "${ADAPTER_SO}" /var/lib/sai-opi/libsai_opi_adapter.so

# systemd drop-in if syncd is a host unit (not docker)
if command -v systemctl >/dev/null && systemctl list-unit-files syncd.service >/dev/null 2>&1; then
  mkdir -p /etc/systemd/system/syncd.service.d
  cat > /etc/systemd/system/syncd.service.d/opi.conf <<EOF
[Service]
EnvironmentFile=-/etc/sonic/opi.env
Environment=OPI_SERVER_ADDRESS=${OPI_SERVER_ADDRESS}
EOF
  systemctl daemon-reload
fi

# --- syncd docker: replace libsai.so inside the container ---
if command -v docker >/dev/null && docker inspect "${SYNCD_CONTAINER}" >/dev/null 2>&1; then
  echo "updating container ${SYNCD_CONTAINER}"
  docker cp "${ADAPTER_SO}" "${SYNCD_CONTAINER}:/tmp/libsai_opi_adapter.so"

  docker exec -i "${SYNCD_CONTAINER}" bash -s <<EOF
set -euo pipefail
for d in /usr/lib /usr/lib/x86_64-linux-gnu /usr/lib/aarch64-linux-gnu /usr/lib/\$(uname -m)-linux-gnu; do
  [[ -d "\$d" ]] || continue
  if [[ -e "\$d/libsai.so" ]]; then
    cp -a "\$d/libsai.so" "\$d/libsai.so.vendor.bak" || true
  fi
  install -m 0755 /tmp/libsai_opi_adapter.so "\$d/libsai_opi_adapter.so"
  ln -sfn libsai_opi_adapter.so "\$d/libsai.so"
done
mkdir -p /etc/sai.d /etc/sonic
cat > /etc/sai.d/opi.env <<ENVEOF
OPI_SERVER_ADDRESS=${OPI_SERVER_ADDRESS}
ENVEOF
cat > /etc/sonic/opi.env <<ENVEOF
OPI_SERVER_ADDRESS=${OPI_SERVER_ADDRESS}
ENVEOF
if [[ -f /etc/sai.d/sai.profile ]]; then
  if grep -q '^OPI_SERVER_ADDRESS=' /etc/sai.d/sai.profile; then
    sed -i 's|^OPI_SERVER_ADDRESS=.*|OPI_SERVER_ADDRESS=${OPI_SERVER_ADDRESS}|' /etc/sai.d/sai.profile
  else
    echo 'OPI_SERVER_ADDRESS=${OPI_SERVER_ADDRESS}' >> /etc/sai.d/sai.profile
  fi
fi
ldconfig || true
EOF

  # supervisord: export the env into the syncd child if a conf exists
  if docker exec "${SYNCD_CONTAINER}" bash -c 'ls /etc/supervisor/conf.d/*.conf >/dev/null 2>&1'; then
    docker exec "${SYNCD_CONTAINER}" bash -c "
      set -e
      for f in /etc/supervisor/conf.d/*.conf; do
        if grep -q '^\[program:syncd\]' \"\$f\" && ! grep -q OPI_SERVER_ADDRESS \"\$f\"; then
          printf '\nenvironment=OPI_SERVER_ADDRESS=\"${OPI_SERVER_ADDRESS}\"\n' >> \"\$f\"
        fi
      done
    " || true
  fi

  if [[ "${RESTART_SYNCD}" -eq 1 ]]; then
    echo "restarting ${SYNCD_CONTAINER} (or systemctl restart swss if you recreate images)"
    docker restart "${SYNCD_CONTAINER}" || true
  fi
else
  echo "docker container '${SYNCD_CONTAINER}' not found; host libsai.so was still replaced"
fi

echo
echo "OPI_SERVER_ADDRESS=${OPI_SERVER_ADDRESS}"
echo "backup of previous libsai: ${backup_dir}"
echo "adapter reads: env OPI_SERVER_ADDRESS, then /etc/sonic/opi.env, /etc/sai.d/opi.env, sai.profile"
echo
echo "Persist across syncd recreate (install once):"
echo "  sudo ./scripts/enable-persistent-adapter.sh --lib ${ADAPTER_SO} --container ${SYNCD_CONTAINER}"
